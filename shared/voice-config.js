/* =============================================================================
   TOUCH E-learning — 发音速度设定  (shared/voice-config.js)
   -----------------------------------------------------------------------------
   这个档案是「后台设定」。学生不会看到任何速度选项 —— 打开课程就是对的速度。

   要调整：用 tools/voice-admin.html（可以边拉边试听），
   调好之後它会给你一段设定，贴到下面的 rate 里，重新发布即可。
   或者你直接改下面的数字也可以，改完要重新发布才会到学生那边。

   -----------------------------------------------------------------------------
   数字怎么看：1 ＝ 原速，0.8 ＝ 放慢两成，1.1 ＝ 快一成。
   浏览器放慢时会保持音高，所以不会变成低沉的怪声。

   建议范围 0.7 ～ 1.1。低於 0.7 会听起来一顿一顿的，
   而且学生会学到不自然的节奏 —— 真实对话没有人那样讲话。

   -----------------------------------------------------------------------------
   之後接 Supabase：这些设定会改成从 Supabase 读（一张 settings 表），
   那时候你在后台改完，学生下次打开就生效，不用重新发布。
   读取的入口只有 shared/voice.js 里的 config() 一个地方，换起来很快。
============================================================================= */

